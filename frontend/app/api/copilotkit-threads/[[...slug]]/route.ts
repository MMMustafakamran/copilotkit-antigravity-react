// Doc: /google-antigravity/headless-threads, step 1 "server.ts" (verbatim below the HARNESS block).
// Also the runtime behind the Threads Drawer page, which says to connect the runtime to Intelligence
// but shows no runtime code of its own.
// HARNESS (begin): the snippet uses `agent` and `verifyAppSession` but never defines them, and
// shows no route/handler (FINDINGS.md #69). Minimal stand-ins so the route can load at all:
import { HttpAgent } from "@ag-ui/client";
import { createCopilotRuntimeHandler } from "@copilotkit/runtime/v2";
const agent = new HttpAgent({ url: "http://localhost:8040" }); // HARNESS: the quickstart agent (backend/main.py on :8040)
async function verifyAppSession(_request: Request) {
  return { user: { id: "antigravity-qa-user", name: "Antigravity QA" } }; // HARNESS: no auth in this harness
}
// HARNESS (end)

import {
  CopilotKitIntelligence,
  CopilotRuntime,
} from "@copilotkit/runtime/v2";

const runtime = new CopilotRuntime({
  agents: {
    default: agent,
    // HARNESS: the root layout's <CopilotKit agent="antigravity_agent"> (quickstart) is the chat
    // configuration both Threads pages inherit, so the drawer and chat resolve "antigravity_agent".
    antigravity_agent: agent,
  },
  // Without `intelligence` the runtime runs in SSE mode and the thread
  // UI has nothing to list — chat still works, so this fails quietly.
  intelligence: new CopilotKitIntelligence({
    apiKey: process.env.CPK_INTELLIGENCE_API_KEY!,
  }),
  // Required alongside `intelligence`: threads are scoped per user, so
  // without this every visitor shares one history. Resolve the real
  // signed-in user — see Thread & History Lifecycle.
  identifyUser: async (request) => {
    const session = await verifyAppSession(request);
    if (!session?.user) throw new Error("Unauthorized");
    return { id: session.user.id, name: session.user.name };
  },
  // Thread names are auto-generated by default.
  // Set to false to disable:
  // generateThreadNames: false,

  // Optional: tune thread lock behavior
  // lockTtlSeconds: 20,              // Lock TTL (default 20s, max 3600s)
  // lockHeartbeatIntervalSeconds: 15, // Heartbeat interval (default 15s, max 3000s)
  // lockKeyPrefix: "my-app",          // Custom Redis key prefix for the lock
});

// HARNESS: Next.js bindings (the doc shows none for server.ts).
const handler = createCopilotRuntimeHandler({ runtime, basePath: "/api/copilotkit-threads" });
export const GET = handler;
export const POST = handler;
export const PATCH = handler;
export const DELETE = handler;
